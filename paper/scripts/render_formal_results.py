#!/usr/bin/env python3
"""Render auditable LaTeX result macros from the formal campaign audit."""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path
from typing import Any


def _macro(name: str, value: Any) -> str:
    return rf"\providecommand{{\{name}}}{{{value}}}"


def _pct(value: float, digits: int = 2) -> str:
    return f"{100.0 * value:.{digits}f}"


def _median(values: list[float], digits: int = 2) -> str:
    return f"{statistics.median(values):.{digits}f}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    payload = json.loads(Path(args.input).read_text(encoding="utf-8"))
    if payload.get("status") != "passed":
        raise SystemExit("formal campaign audit has not passed")

    baseline = payload["baseline"]
    diagnostics = payload["baseline_diagnostics"]
    comparison = baseline["comparisons"]["full_resident"]
    if comparison.get("status") != "passed":
        raise SystemExit("full-resident/LatchMoE comparison is not reportable")
    unsupported = {}
    for arm in ("native_prefetch", "legacy_layered"):
        rows = [row for row in diagnostics if row["arm"] == arm]
        unsupported[arm] = sum(
            int((row.get("exactness") or {}).get("mismatched_count") or 0)
            for row in rows
        )

    lines = ["% Generated by paper/scripts/render_formal_results.py; do not edit."]
    workload = payload["workload"]
    lines.extend([
        _macro("FormalRequestsPerBaselineUnit", diagnostics[0]["successful_requests"]),
        _macro("FormalRequestsPerBaselineArm", sum(
            int(row["successful_requests"]) for row in diagnostics
            if row["arm"] == "full_resident"
        )),
        _macro("FormalPromptMin", workload["prompt_tokens_min"]),
        _macro("FormalPromptMedian", f"{workload['prompt_tokens_p50']:.0f}"),
        _macro("FormalPromptMax", workload["prompt_tokens_max"]),
        _macro("NativeMismatchRequests", unsupported["native_prefetch"]),
        _macro("LegacyMismatchRequests", unsupported["legacy_layered"]),
    ])
    for arm, prefix in (("full_resident", "FullResident"), ("latchmoe", "Latch")):
        repeats = baseline["arms"][arm]
        diag = [row for row in diagnostics if row["arm"] == arm]
        lines.extend([
            _macro(prefix + "TTFTMedian", _median([float(row["ttft_p50_ms"]) for row in repeats])),
            _macro(prefix + "TTFTTail", _median([float(row["ttft_p95_ms"]) for row in repeats])),
            _macro(prefix + "TPOTMedian", _median([float(row["tpot_p50_ms"]) for row in repeats])),
            _macro(prefix + "HBMPeak", f"{statistics.median(float(row['hbm_peak_percent']) for row in diag):.0f}"),
        ])
    lines.extend([
        _macro("LatchVsFullTTFTEffect", _pct(comparison["ttft_effect"])),
        _macro("LatchVsFullTTFTLower", _pct(comparison["ttft_interval_95"]["lower"])),
        _macro("LatchVsFullTTFTUpper", _pct(comparison["ttft_interval_95"]["upper"])),
        _macro("LatchVsFullTPOTEffect", _pct(comparison["tpot_effect"])),
        _macro("LatchVsFullTPOTLower", _pct(comparison["tpot_interval_95"]["lower"])),
        _macro("LatchVsFullTPOTUpper", _pct(comparison["tpot_interval_95"]["upper"])),
    ])

    issue = payload["issue17"]
    bounded = issue["paired_statistics"]
    lines.extend([
        _macro("BoundedRequestsPerUnit", issue["packaged_arms"]["full_layer"]["successful_requests"] // 3),
        _macro("BoundedTotalRequests", sum(
            int(arm["successful_requests"]) for arm in issue["packaged_arms"].values()
        )),
        _macro("BoundedTotalTokens", sum(
            int(arm["output_tokens"]) for arm in issue["packaged_arms"].values()
        )),
        _macro("BoundedTTFTEffect", _pct(bounded["ttft"]["estimate"])),
        _macro("BoundedTTFTLower", _pct(bounded["ttft"]["interval"]["lower"])),
        _macro("BoundedTTFTUpper", _pct(bounded["ttft"]["interval"]["upper"])),
        _macro("BoundedTPOTEffect", _pct(bounded["tpot"]["estimate"])),
        _macro("BoundedTPOTLower", _pct(bounded["tpot"]["interval"]["lower"])),
        _macro("BoundedTPOTUpper", _pct(bounded["tpot"]["interval"]["upper"])),
        _macro("BoundedRepeatMedianTTFTReduction", f"{issue['packaged_comparison']['ttft_p50_reduction_percent']:.2f}"),
        _macro("BoundedRepeatTailTTFTReduction", f"{issue['packaged_comparison']['ttft_p95_reduction_percent']:.2f}"),
    ])

    overlap = payload["overlap"]["statistics"]
    lines.extend([
        _macro("OverlapRequestsPerUnit", payload["overlap"]["units"][0]["requests"]["successful"]),
        _macro("OverlapTotalRequests", sum(
            int(unit["requests"]["successful"]) for unit in payload["overlap"]["units"]
        )),
        _macro("OverlapTTFTEffect", _pct(overlap["ttft"]["estimate"])),
        _macro("OverlapTTFTLower", _pct(overlap["ttft"]["interval"]["lower"])),
        _macro("OverlapTTFTUpper", _pct(overlap["ttft"]["interval"]["upper"])),
        _macro("OverlapTPOTEffect", _pct(overlap["tpot"]["estimate"])),
        _macro("OverlapTPOTLower", _pct(overlap["tpot"]["interval"]["lower"])),
        _macro("OverlapTPOTUpper", _pct(overlap["tpot"]["interval"]["upper"])),
    ])

    capacity_prefix = {16: "SlotsSixteen", 32: "SlotsThirtyTwo", 64: "SlotsSixtyFour"}
    for row in payload["capacity"]["rows"]:
        prefix = capacity_prefix[int(row["slots"])]
        lines.extend([
            _macro(prefix + "TTFTMedian", f"{float(row['ttft_p50_ms']):.2f}"),
            _macro(prefix + "TTFTTail", f"{float(row['ttft_p95_ms']):.2f}"),
            _macro(prefix + "TPOTMedian", f"{float(row['tpot_p50_ms']):.2f}"),
            _macro(prefix + "Waves", int(row["waves_total"])),
            _macro(prefix + "HtwoDGiB", f"{int(row['h2d_bytes']) / 1024**3:.1f}"),
            _macro(prefix + "SlotGiB", f"{int(row['slot_bank_bytes']) / 1024**3:.2f}"),
            _macro(prefix + "HBMPeak", int(row["hbm_peak_percent"])),
        ])
    lines.append(_macro("CapacityRequests", payload["capacity"]["rows"][0]["successful_requests"]))
    low, high = payload["capacity"]["rows"][0], payload["capacity"]["rows"][-1]
    lines.extend([
        _macro("CapacityTTFTMedianReduction", f"{100.0 * (1.0 - high['ttft_p50_ms'] / low['ttft_p50_ms']):.2f}"),
        _macro("CapacityTTFTTailReduction", f"{100.0 * (1.0 - high['ttft_p95_ms'] / low['ttft_p95_ms']):.2f}"),
    ])

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
